-- Actual payments and AI usage evidence. Append-only migration; existing records are preserved.

ALTER TABLE subscriptions.subscription_reviews
    ADD COLUMN usage_complete boolean NOT NULL DEFAULT false,
    ADD COLUMN hourly_value double precision CHECK (hourly_value IS NULL OR hourly_value >= 0),
    ADD COLUMN value_currency text CHECK (value_currency IS NULL OR length(value_currency) <= 12);

CREATE INDEX subscriptions_category ON subscriptions.subscriptions (workspace_id, category);

CREATE TABLE subscriptions.subscription_usages (
    workspace_id             uuid NOT NULL,
    id                       bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000),
    legacy_id                bigint,
    subscription_id          bigint NOT NULL,
    used_on                  date NOT NULL,
    title                    text NOT NULL CHECK (length(title) <= 200 AND length(title) >= 1),
    outcome                  text NOT NULL DEFAULT 'completed' CHECK (outcome IN ('completed', 'partial', 'discarded')),
    baseline_minutes         double precision CHECK (baseline_minutes IS NULL OR (baseline_minutes >= 0)),
    actual_minutes           double precision CHECK (actual_minutes IS NULL OR (actual_minutes >= 0)),
    rework_minutes           double precision NOT NULL DEFAULT 0 CHECK (rework_minutes >= 0),
    task_ref                 text CHECK (task_ref IS NULL OR (length(task_ref) <= 300)),
    evidence                 text CHECK (evidence IS NULL OR (length(evidence) <= 1500)),
    source                   text NOT NULL DEFAULT 'manual' CHECK (length(source) <= 80),
    source_ref               text CHECK (source_ref IS NULL OR (length(source_ref) <= 300)),
    version                  bigint NOT NULL DEFAULT 1,
    created_at               timestamptz NOT NULL DEFAULT now(),
    updated_at               timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (workspace_id, id),
    FOREIGN KEY (workspace_id, subscription_id) REFERENCES subscriptions.subscriptions (workspace_id, id)
);
CREATE UNIQUE INDEX subscription_usages_legacy ON subscriptions.subscription_usages (workspace_id, legacy_id) WHERE legacy_id IS NOT NULL;
CREATE INDEX subscription_usages_outcome ON subscriptions.subscription_usages (workspace_id, outcome);
CREATE INDEX subscription_usages_subscription_id ON subscriptions.subscription_usages (workspace_id, subscription_id);

CREATE TABLE subscriptions.subscription_charges (
    workspace_id             uuid NOT NULL,
    id                       bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000),
    legacy_id                bigint,
    subscription_id          bigint NOT NULL,
    paid_on                  date NOT NULL,
    period_start             date NOT NULL,
    period_end               date NOT NULL,
    amount                   double precision NOT NULL CHECK (amount >= 0),
    currency                 text NOT NULL CHECK (length(currency) <= 12 AND length(currency) >= 1),
    evidence                 text NOT NULL CHECK (length(evidence) <= 1500 AND length(evidence) >= 1),
    source                   text NOT NULL DEFAULT 'manual' CHECK (length(source) <= 80),
    source_ref               text CHECK (source_ref IS NULL OR (length(source_ref) <= 300)),
    version                  bigint NOT NULL DEFAULT 1,
    created_at               timestamptz NOT NULL DEFAULT now(),
    updated_at               timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (workspace_id, id),
    FOREIGN KEY (workspace_id, subscription_id) REFERENCES subscriptions.subscriptions (workspace_id, id)
);
CREATE UNIQUE INDEX subscription_charges_legacy ON subscriptions.subscription_charges (workspace_id, legacy_id) WHERE legacy_id IS NOT NULL;
CREATE INDEX subscription_charges_subscription_id ON subscriptions.subscription_charges (workspace_id, subscription_id);

ALTER TABLE subscriptions.subscription_charges
    ADD CONSTRAINT subscription_charges_service_period CHECK (period_start <= period_end);

-- Let idempotent create reservations use the new resource kinds as well.

ALTER TABLE subscriptions.create_keys DROP CONSTRAINT create_keys_kind_check;

ALTER TABLE subscriptions.create_keys ADD CONSTRAINT create_keys_kind_check
    CHECK (kind IN ('subscription', 'subscription-review', 'subscription-alias',
                    'subscription-usage', 'subscription-charge'));

DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['subscription_usages', 'subscription_charges'] LOOP
        EXECUTE format('ALTER TABLE subscriptions.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE subscriptions.%I FORCE ROW LEVEL SECURITY', t);
        EXECUTE format('CREATE POLICY workspace_isolation ON subscriptions.%I'
                       ' USING (workspace_id = subscriptions.current_workspace())'
                       ' WITH CHECK (workspace_id = subscriptions.current_workspace())', t);
    END LOOP;
END
$$;

GRANT SELECT, INSERT, UPDATE, DELETE ON subscriptions.subscription_usages, subscriptions.subscription_charges TO subscriptions_api;

GRANT USAGE ON SEQUENCE subscriptions.subscription_usages_id_seq, subscriptions.subscription_charges_id_seq TO subscriptions_api;
